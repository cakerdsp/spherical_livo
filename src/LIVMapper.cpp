void LIVMapper::initializeComponents(ros::NodeHandle &nh) 
{
  downSizeFilterSurf.setLeafSize(filter_size_surf_min, filter_size_surf_min, filter_size_surf_min);
  extT << VEC_FROM_ARRAY(extrinT);
  extR << MAT_FROM_ARRAY(extrinR);

  voxelmap_manager->extT_ << VEC_FROM_ARRAY(extrinT);
  voxelmap_manager->extR_ << MAT_FROM_ARRAY(extrinR);

  for (int id=0; id<num_cameras; ++id)
  {
    const std::string key="cameras/camera"+std::to_string(id);
    const auto ns=parameter<std::string>(nh,key+"/camera_ns","camera"+std::to_string(id));
    VIOManager::CameraView view;
    view.camera=std::make_shared<SphericalCamera>(cameraModel(nh,ns));
    view.Rcl=rotation(nh,key+"/Rcl"); view.Pcl=translation(nh,key+"/Pcl");
    vio_manager->cameras_.push_back(std::move(view));
    camera_time_offsets.push_back(parameter(nh,key+"/time_offset",0.0));
    const auto topic=parameter<std::string>(nh,key+"/img_topic","");
    if(topic.empty()) throw std::invalid_argument(key+"/img_topic is required");
    image_topics.push_back(topic);
  }
  vio_manager->patch_radius=parameter(nh,"visual/patch_radius_deg",0.9)*M_PI/180.0;
  vio_manager->sample_count=parameter(nh,"visual/patch_samples",48);
  vio_manager->max_patches=parameter(nh,"visual/max_patches",120);
  vio_manager->map_voxel_size=voxelmap_manager->config_setting_.max_voxel_size_;
  vio_manager->range_noise=voxelmap_manager->config_setting_.dept_err_;

  vio_manager->grid_size = grid_size;
  vio_manager->patch_size = patch_size;
  vio_manager->outlier_threshold = outlier_threshold;
  vio_manager->setImuToLidarExtrinsic(extT, extR);

  vio_manager->state = &_state;
  vio_manager->state_propagat = &state_propagat;
  vio_manager->max_iterations = max_iterations;
  vio_manager->img_point_cov = IMG_POINT_COV;
  vio_manager->normal_en = normal_en;
  vio_manager->inverse_composition_en = inverse_composition_en;
  vio_manager->raycast_en = raycast_en;

  vio_manager->grid_n_height = grid_n_height;
  vio_manager->patch_pyrimid_level = patch_pyrimid_level;
  vio_manager->exposure_estimate_en = exposure_estimate_en;
  vio_manager->colmap_output_en = colmap_output_en;
  vio_manager->activateCamera(0);
  p_imu->lidar_type = p_pre->lidar_type;

  p_imu->set_extrinsic(extT, extR);
  p_imu->set_gyr_cov_scale(V3D(gyr_cov, gyr_cov, gyr_cov));
  p_imu->set_acc_cov_scale(V3D(acc_cov, acc_cov, acc_cov));
  p_imu->set_inv_expo_cov(inv_expo_cov);
  p_imu->set_gyr_bias_cov(V3D::Constant(parameter(nh,"imu/b_gyr_cov",0.0001)));
  p_imu->set_acc_bias_cov(V3D::Constant(parameter(nh,"imu/b_acc_cov",0.0001)));
  p_imu->set_imu_init_frame_num(imu_int_frame);

  if (!imu_en) p_imu->disable_imu();
  if (!gravity_est_en) p_imu->disable_gravity_est();
  if (!ba_bg_est_en) p_imu->disable_bias_est();
  if (!exposure_estimate_en) p_imu->disable_exposure_est();

  slam_mode_ = (img_en && lidar_en) ? LIVO : imu_en ? ONLY_LIO : ONLY_LO;
}

